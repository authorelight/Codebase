// Generates js/content-bundle.js containing all course content (.json / .md) and Python
// harnesses (.py) as an on-demand fallback module in case static hosts omit or block .md/.py files.
//   node tools/build-content.mjs

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(root, 'js', 'content-bundle.js');

const entries = {};

function walk(relDir, allowedExts) {
  const absDir = path.join(root, relDir);
  if (!fs.existsSync(absDir)) return;
  for (const name of fs.readdirSync(absDir).sort()) {
    if (name.startsWith('.')) continue;
    const rel = `${relDir}/${name}`;
    const abs = path.join(root, rel);
    const st = fs.statSync(abs);
    if (st.isDirectory()) {
      walk(rel, allowedExts);
    } else if (st.isFile() && allowedExts.has(path.extname(name).toLowerCase())) {
      entries[rel] = fs.readFileSync(abs, 'utf8');
    }
  }
}

walk('content', new Set(['.json', '.md']));
walk('games/harness', new Set(['.py']));

const hostPyRel = 'js/py/host.py';
const hostPyAbs = path.join(root, hostPyRel);
if (fs.existsSync(hostPyAbs)) {
  entries[hostPyRel] = fs.readFileSync(hostPyAbs, 'utf8');
}

const header = '// Auto-generated by tools/build-content.mjs — fallback bundle for hosts that do not serve raw .md/.py files.\n';
const body = `export const CONTENT_BUNDLE = ${JSON.stringify(entries)};\n`;
fs.writeFileSync(outFile, header + body, 'utf8');

const count = Object.keys(entries).length;
const kb = Math.round(Buffer.byteLength(header + body, 'utf8') / 1024);
console.log(`Built js/content-bundle.js (${count} files, ${kb} KB)`);
